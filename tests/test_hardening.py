"""Tests for Phase 4 hardening: Web Bot Auth, per-purpose policy, middleware.

The Ed25519 test vector was generated with OpenSSL (an independent
implementation), not with this module: keypair generated by openssl,
message "hello doorman" signed by openssl, then verified here.
"""

from __future__ import annotations

import base64
import os

from doorman.middleware import DoormanMiddleware, decide
from doorman.policy import ALLOW, BLOCK, Policy, PolicyRule
from doorman.watch import load_vendors
from doorman.webauth import verify_bot_auth, verify_ed25519

FIXTURES = os.path.join(os.path.dirname(__file__), "..", "fixtures")

# OpenSSL-generated vector: Ed25519 keypair, message b"hello doorman".
OPENSSL_PUBLIC_KEY = bytes.fromhex(
    "7717f7b3b83f8f00e033e919aab78cb3c006dd4a1be1894d49f34878fa1c60ad"
)
OPENSSL_MESSAGE = b"hello doorman"
OPENSSL_SIGNATURE = bytes.fromhex(
    "380e46192290136dc9839a25ca05dd78da06f548453d8fa68178a8c570b78f9cc"
    "649b686812507ee0f50e5c311f9ed4ff84919e760356d8ee08994751fcf7906"
)


def _vendors():
    return load_vendors(os.path.join(FIXTURES, "vendor_ips.json"))


def test_ed25519_openssl_vector_verifies():
    assert verify_ed25519(OPENSSL_PUBLIC_KEY, OPENSSL_MESSAGE, OPENSSL_SIGNATURE)


def test_ed25519_tampered_message_fails():
    assert not verify_ed25519(OPENSSL_PUBLIC_KEY, b"hello doorman!", OPENSSL_SIGNATURE)


def test_ed25519_tampered_signature_fails():
    tampered = bytearray(OPENSSL_SIGNATURE)
    tampered[0] ^= 1
    assert not verify_ed25519(OPENSSL_PUBLIC_KEY, OPENSSL_MESSAGE, bytes(tampered))


def test_ed25519_wrong_lengths_fail():
    assert not verify_ed25519(b"short", OPENSSL_MESSAGE, OPENSSL_SIGNATURE)
    assert not verify_ed25519(OPENSSL_PUBLIC_KEY, OPENSSL_MESSAGE, b"short")


def test_bot_auth_header_verifies():
    headers = {
        "Signature": "sig1=:" + base64.b64encode(OPENSSL_SIGNATURE).decode() + ":",
        "Signature-Agent": "test-key",
    }
    verified, reason = verify_bot_auth(
        headers, OPENSSL_MESSAGE, lambda key_id: OPENSSL_PUBLIC_KEY if key_id == "test-key" else None
    )
    assert verified, reason


def test_bot_auth_missing_headers_fail():
    verified, _ = verify_bot_auth({}, OPENSSL_MESSAGE, lambda key_id: None)
    assert not verified


def test_policy_blocks_training_allows_search():
    policy = Policy(
        rules=[
            PolicyRule(agent="GPTBot", purpose="training", action=BLOCK),
            PolicyRule(agent="*", purpose="search", action=ALLOW),
        ],
        default=ALLOW,
    )
    assert policy.evaluate("GPTBot", "training") == BLOCK
    assert policy.evaluate("OAI-SearchBot", "search") == ALLOW
    assert policy.evaluate("ChatGPT-User", "agent-fetch") == ALLOW


def test_policy_default_purpose_mapping():
    policy = Policy(default=ALLOW)
    assert policy.purpose_for("GPTBot") == "training"
    assert policy.purpose_for("OAI-SearchBot") == "search"
    assert policy.purpose_for("UnknownBot") is None


def test_decide_spoofed_blocked():
    action, result = decide("203.0.113.200", "ChatGPT-User/1.0", _vendors())
    assert action == BLOCK
    assert result.label == "spoofed_agent"


def test_decide_verified_allowed_without_policy():
    action, result = decide("203.0.113.10", "ChatGPT-User/1.0", _vendors())
    assert action == ALLOW
    assert result.label == "verified_agent"


def test_decide_policy_blocks_verified_training():
    policy = Policy(
        rules=[PolicyRule(agent="*", purpose="training", action=BLOCK)],
        default=ALLOW,
    )
    action, _ = decide("198.51.100.20", "ClaudeBot/1.0", _vendors(), policy)
    assert action == BLOCK


def _wsgi_app(environ, start_response):
    body = b"OK"
    start_response("200 OK", [("Content-Type", "text/plain"), ("Content-Length", "2")])
    return [body]


def _call(app, ip, ua):
    captured = {}

    def start_response(status, headers, exc_info=None):
        captured["status"] = status
        captured["headers"] = dict(headers)

    body = b"".join(app({"REMOTE_ADDR": ip, "HTTP_USER_AGENT": ua}, start_response))
    return captured["status"], captured["headers"], body


def test_middleware_blocks_spoofed():
    app = DoormanMiddleware(_wsgi_app, _vendors())
    status, headers, _ = _call(app, "203.0.113.200", "ChatGPT-User/1.0")
    assert status.startswith("403")
    assert headers["X-Doorman-Label"] == "spoofed_agent"


def test_middleware_passes_verified_with_headers():
    app = DoormanMiddleware(_wsgi_app, _vendors())
    status, headers, body = _call(app, "203.0.113.10", "ChatGPT-User/1.0")
    assert status.startswith("200")
    assert body == b"OK"
    assert headers["X-Doorman-Label"] == "verified_agent"
    assert headers["X-Doorman-Agent"] == "ChatGPT-User"


def test_middleware_rate_limits_unknown_bot():
    app = DoormanMiddleware(_wsgi_app, _vendors(), rate_limit_max=2)
    for _ in range(2):
        status, _, _ = _call(app, "203.0.113.180", "EvilScraper/2.0")
        assert status.startswith("200")
    status, _, _ = _call(app, "203.0.113.180", "EvilScraper/2.0")
    assert status.startswith("429")
